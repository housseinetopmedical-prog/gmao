CREATE TABLE IF NOT EXISTS `marches` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `equipmentId` int(11) DEFAULT NULL,
  `organism` varchar(191) NOT NULL,
  `marketNumber` varchar(191) NOT NULL,
  `lot` varchar(191) DEFAULT NULL,
  `designation` varchar(191) NOT NULL,
  `brand` varchar(191) NOT NULL,
  `model` varchar(191) NOT NULL,
  `serialNumber` varchar(191) NOT NULL,
  `inventoryNumber` varchar(191) NOT NULL,
  `articleCode` varchar(191) DEFAULT NULL,
  `hospital` varchar(191) NOT NULL,
  `city` varchar(191) NOT NULL,
  `sector` varchar(191) NOT NULL,
  `contractType` varchar(191) NOT NULL,
  `contractStartDate` datetime(3) DEFAULT NULL,
  `contractEndDate` datetime(3) DEFAULT NULL,
  `documentUrl` text DEFAULT NULL,
  `createdAt` datetime(3) NOT NULL DEFAULT current_timestamp(3),
  `updatedAt` datetime(3) NOT NULL DEFAULT current_timestamp(3) ON UPDATE current_timestamp(3),
  PRIMARY KEY (`id`),
  KEY `marches_equipmentId_idx` (`equipmentId`),
  KEY `marches_inventoryNumber_idx` (`inventoryNumber`),
  CONSTRAINT `marches_equipmentId_fkey` FOREIGN KEY (`equipmentId`) REFERENCES `materiels` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
